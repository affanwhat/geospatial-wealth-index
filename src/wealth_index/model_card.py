"""Model card: a Markdown summary of one training run, filled from its saved outputs."""

from __future__ import annotations

import json
import os
from pathlib import Path

import pandas as pd

from wealth_index.report import _search_summary

MODEL_NAMES = {
    "tuned": "Tuned model",
    "rf_default": "RandomForest, default settings",
    "linear_regression": "Linear regression baseline",
}

INTENDED_USE = """\
- **For:** comparing relative wealth between villages (kelurahan/desa) in Jabodetabek, e.g. to
  prioritise field surveys or check where official statistics may be out of date.
- **Not for:** judging individual households, ranking villages for punitive decisions, or areas
  outside Jabodetabek. The model has only seen this metropolitan area.
- **Unit:** one value per village. It cannot show inequality inside a village."""

LIMITATIONS = """\
- **Labels are an index, not income.** The target is a composite wealth index built from Podes
  village survey indicators. It inherits that survey's coverage and reporting errors.
- **Uneven inputs.** OpenStreetMap is mapped more densely in central Jakarta than on the rural
  fringe, so OSM features carry more signal there. Night-time light saturates in dense cores.
- **Single snapshot.** Imagery and labels describe one period. The model does not track change.
- **Large villages are averaged.** Rural villages cover far more ground than urban ones, so one
  value hides more variation there.
- **Spatial errors.** Errors are likely to cluster. Check the residuals before trusting a region."""

ETHICS = """\
- A low score is a prediction, not a measurement. Confirm on the ground before acting on it.
- Don't publish the map in a way that labels named communities as poor without context.
- BPS Podes microdata is licensed for private use. This card reports only aggregate results."""


def _fmt(x: float, decimals: int = 3) -> str:
    return f"{x:.{decimals}f}"


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _link(target: Path, card: Path) -> str:
    return Path(os.path.relpath(target.resolve(), card.resolve().parent)).as_posix()


def build_model_card(
    run_dir: str | Path,
    output: str | Path,
    *,
    predictions: str | Path | None = None,
    map_png: str | Path | None = None,
    top_n: int = 10,
) -> Path:
    """Write the model card for run_dir; predictions and map are included when they exist."""
    run_dir, output = Path(run_dir), Path(output)
    files = [run_dir / f for f in ("metrics.json", "metadata.json", "feature_importance.csv")]
    missing = [f.name for f in files if not f.exists()]
    if missing:
        raise FileNotFoundError(f"{run_dir} is missing {missing}; is it a complete training run?")
    metrics = json.loads(files[0].read_text())
    meta = json.loads(files[1].read_text())
    importance = pd.read_csv(files[2])
    cfg = meta["config"]
    search, cv = metrics["search"], metrics["cv_comparison"]
    tuned_test, tuned_train = metrics["test"]["tuned"], metrics["train"]["tuned"]

    sections = [
        "# Model card: village wealth index, Jabodetabek",
        f"Generated by `wi model-card` from training run `{run_dir.name}`.",
        "## Model details",
        "\n".join(
            [
                "- **Task:** regression of a village wealth index from geospatial features.",
                f"- **Search:** `{search['method']}`, scored by `{search['scoring']}`.",
                f"- **Best model:** {_search_summary(search)}",
                f"- **Trained:** {meta['created_at']}",
                f"- **Code version:** git `{meta.get('git_sha') or 'unknown'}`",
                "- **Libraries:** "
                + ", ".join(f"{k} {v}" for k, v in meta.get("versions", {}).items()),
            ]
        ),
        "## Intended use",
        INTENDED_USE,
        "## Data",
        "\n".join(
            [
                f"- **Dataset:** `{cfg['data']['path']}` (sha256 `{meta['data_sha256'][:12]}…`)",
                f"- **Target:** `{cfg['data']['target_col']}`",
                f"- **Villages:** {meta['n_train']} train, {meta['n_test']} test",
                f"- **Features:** {len(meta['features_in'])} in, "
                f"{len(meta['selected_features'])} kept by feature selection",
                "- **Sources:** Sentinel-2 (spectral indices, texture), SDGSAT-1 or VIIRS"
                " night-time light, OpenStreetMap (POIs, roads, buildings), village boundaries.",
            ]
        ),
        "## Evaluation",
        f"The test set is {cfg['split']['scheme']}: villages are grouped into "
        f"{cfg['split']['block_size_km']:g} km blocks ({meta['n_spatial_blocks']} in total) and "
        f"{cfg['split']['test_size']:.0%} of the blocks are held out, so test villages are not "
        "neighbours of training villages.",
        _table(
            ["Model", "RMSE", "MAE", "R²", "Relative RMSE"],
            [
                [
                    MODEL_NAMES.get(name, name),
                    _fmt(m["rmse"]),
                    _fmt(m["mae"]),
                    _fmt(m["r2"]),
                    f"{m['rrmse_pct']:.1f}%",
                ]
                for name, m in metrics["test"].items()
            ],
        ),
        "\n".join(
            [
                f"- **Overfitting:** the tuned model's RMSE is {_fmt(tuned_train['rmse'])} on "
                f"training villages and {_fmt(tuned_test['rmse'])} on test villages.",
                f"- **Spatial vs random CV:** {cfg['split']['cv_folds']}-fold CV RMSE is "
                f"{_fmt(cv['random']['rmse_mean'])} ± {_fmt(cv['random']['rmse_std'])} with random "
                f"folds and {_fmt(cv['spatial']['rmse_mean'])} ± {_fmt(cv['spatial']['rmse_std'])}"
                " with spatial blocks. The difference is how much a random split would overstate"
                " accuracy.",
            ]
        ),
        "## Most important features",
        f"Permutation importance on the test set (top {top_n}).",
        _table(
            ["Feature", "Importance", "Std", "Kept by selection"],
            [
                [
                    f"`{r.feature}`",
                    _fmt(r.importance_mean, 4),
                    _fmt(r.importance_std, 4),
                    "yes" if r.selected else "no",
                ]
                for r in importance.head(top_n).itertuples()
            ],
        ),
    ]

    if predictions is not None and Path(predictions).exists():
        values = pd.read_csv(predictions).iloc[:, -1]
        q = values.quantile([0.25, 0.5, 0.75])
        sections += [
            "## Predictions",
            f"`{Path(predictions).as_posix()}`: {len(values)} villages, predicted index from "
            f"{_fmt(values.min(), 1)} to {_fmt(values.max(), 1)} (quartiles {_fmt(q[0.25], 1)}, "
            f"{_fmt(q[0.5], 1)}, {_fmt(q[0.75], 1)}).",
        ]
        if map_png is not None and Path(map_png).exists():
            sections.append(f"![Predicted wealth index]({_link(Path(map_png), output)})")

    sections += ["## Limitations", LIMITATIONS, "## Ethical considerations", ETHICS]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n\n".join(sections) + "\n", encoding="utf-8")
    return output
